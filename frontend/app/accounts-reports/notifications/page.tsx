"use client";

import Link from "next/link";
import { useState } from "react";
import { KEYS } from "@/lib/seed";
import { loadList, saveList, useStoredList } from "@/lib/storage";
import type { NotificationItem } from "@/lib/types";

export default function NotificationsPage() {
  const notifications = useStoredList<NotificationItem>(KEYS.notifications, []);
  const [unreadOnly, setUnreadOnly] = useState(false);
  const unreadCount = notifications.filter((item) => !item.readAt).length;
  const shown = notifications.filter((item) => !unreadOnly || !item.readAt);

  function markRead(id: string) {
    const updated = loadList<NotificationItem>(KEYS.notifications, []).map((item) =>
      item.id === id ? { ...item, readAt: new Date().toISOString() } : item,
    );
    saveList(KEYS.notifications, updated);
  }

  function markAllRead() {
    saveList(KEYS.notifications, loadList<NotificationItem>(KEYS.notifications, []).map((item) =>
      item.readAt ? item : { ...item, readAt: new Date().toISOString() },
    ));
  }

  return (
    <main className="module-shell">
      <header className="module-intro">
        <p className="module-eyebrow">PASSENGER ACCOUNT · MOCKUP</p>
        <h1>Notifications <span className="module-count">{unreadCount} unread</span></h1>
        <p>Booking and payment updates generated by this local demonstration.</p>
        <div className="module-shortcuts"><Link href="/accounts-reports/home">Account home</Link><Link href="/accounts-reports/profile">Passenger profile</Link></div>
      </header>
      <section className="module-section">
        <div className="module-section-heading">
          <label className="map-route-filter"><input type="checkbox" checked={unreadOnly} onChange={(event) => setUnreadOnly(event.target.checked)} /> Unread only</label>
          <button className="secondary-button" type="button" onClick={markAllRead} disabled={!unreadCount}>Mark all read</button>
        </div>
        {shown.length === 0 ? <p className="module-empty">No notifications to show. A simulated booking update will appear here.</p> : (
          <div className="admin-record-list">
            {shown.map((item) => (
              <article key={item.id}>
                <div><strong>{item.title}{!item.readAt && <span className="optional-label"> · New</span>}</strong><small>{item.message}</small><small>{new Date(item.createdAt).toLocaleString()}</small></div>
                {!item.readAt && <button className="text-action" type="button" onClick={() => markRead(item.id)}>Mark read</button>}
              </article>
            ))}
          </div>
        )}
        <p className="module-footnote">These messages are stored only in this browser; push notifications and cross-device sync are not connected in this mockup.</p>
      </section>
    </main>
  );
}
